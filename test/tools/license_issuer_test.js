#!/usr/bin/env node
'use strict';

/**
 * FEAT-011 — اختبارات مُصدِّر التراخيص.
 *
 *   node test/tools/license_issuer_test.js
 *
 * تغطي: claims التسعة · exp الصحيح لكل نوع · رفض المسارات المحمية ·
 * رفض مفتاح الاختبار · حتمية التوقيع · الحالات الحدية.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const ISSUER = path.join(REPO_ROOT, 'tools', 'license_issuer.js');
const DAY = 86400;

let passed = 0;
const failures = [];

function check(name, fn) {
  try {
    fn();
    passed++;
    console.log('  ok   ' + name);
  } catch (e) {
    failures.push(name + ' → ' + e.message);
    console.log('  FAIL ' + name + ' → ' + e.message);
  }
}

function assert(cond, message) {
  if (!cond) throw new Error(message || 'assertion failed');
}

function equal(actual, expected, message) {
  if (actual !== expected) {
    throw new Error((message || 'not equal') + ': got ' + actual + ', want ' + expected);
  }
}

// ── fixtures: a throwaway RSA key OUTSIDE the repo ─────────────────────────
// Production keys are never generated by this suite. This key exists only for
// the duration of the run, lives in the OS temp dir, and is deleted with it.
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'madar_issuer_test_'));
const keyPath = path.join(tmpDir, 'issuer_test_key.pem');
const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
  modulusLength: 2048,
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  publicKeyEncoding: { type: 'spki', format: 'pem' },
});
fs.writeFileSync(keyPath, privateKey);
fs.writeFileSync(path.join(tmpDir, 'issuer_test_public.pem'), publicKey);

const outPath = path.join(tmpDir, 'out.madarlicense');

function run(args) {
  try {
    const stdout = execFileSync(process.execPath, [ISSUER].concat(args), {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { code: 0, stdout, stderr: '' };
  } catch (e) {
    return {
      code: e.status,
      stdout: e.stdout || '',
      stderr: e.stderr || '',
    };
  }
}

function decode(segment) {
  return JSON.parse(Buffer.from(segment, 'base64url').toString('utf8'));
}

function readEnvelope(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function claimsOf(env) {
  const parts = env.lease.split('.');
  return { header: decode(parts[0]), payload: decode(parts[1]), signature: parts[2] };
}

function issue(extra) {
  const r = run([
    '--type', 'trial',
    '--days', '7',
    '--machine-guid', 'TEST-MACHINE-1',
    '--features', 'pos,cash_sales,inventory',
    '--key', keyPath,
    '--out', outPath,
  ].concat(extra || []));
  assert(r.code === 0, 'issuer failed: ' + (r.stderr || r.stdout));
  return r;
}

/** Same, but with a clean slate so --days / --months do not collide. */
function issueWith(args) {
  const r = run(
    ['--machine-guid', 'TEST-MACHINE-1', '--key', keyPath, '--out', outPath].concat(args),
  );
  assert(r.code === 0, 'issuer failed: ' + (r.stderr || r.stdout));
  return r;
}

console.log('\nFEAT-011 — license_issuer\n');

// ── AC1 / AC2 / AC3: output shape and term ────────────────────────────────
check('AC1  a trial document is produced and is a valid RS256 JWT', () => {
  issue();
  const env = readEnvelope(outPath);
  const { header, payload } = claimsOf(env);
  equal(header.alg, 'RS256', 'alg');
  equal(header.typ, 'JWT', 'typ');
  equal(payload.status, 'active', 'status');
  equal(payload.plan, 'trial', 'plan');
});

check('AC1  exactly the nine documented claims, no more and no less', () => {
  const env = readEnvelope(outPath);
  const { payload } = claimsOf(env);
  const keys = Object.keys(payload).sort();
  const expected = [
    'exp', 'features', 'iat', 'install_uuid', 'license_expires_at',
    'license_key', 'machine_guid', 'plan', 'status',
  ];
  equal(keys.join(','), expected.join(','), 'claim set');
});

check('AC2  --months 12 gives exp = iat + 365 days exactly', () => {
  issueWith(['--type', 'paid', '--months', '12', '--features', 'pos']);
  const env = readEnvelope(outPath);
  const { payload } = claimsOf(env);
  equal(payload.exp - payload.iat, 365 * DAY, 'annual term');
  equal(payload.plan, 'yearly', 'plan for a yearly paid license');
});

check('AC2  --days 7 gives exp = iat + 7 days and the clock starts at iat', () => {
  issue();
  const env = readEnvelope(outPath);
  const { payload } = claimsOf(env);
  equal(payload.exp - payload.iat, 7 * DAY, 'trial term');
  const drift = Math.abs(Date.now() / 1000 - payload.iat);
  assert(drift < 120, 'iat must be issuance time, drift=' + drift);
});

check('AC2  a lifetime license uses exp = iat + 36500 days and no expiry date', () => {
  const r = run([
    '--type', 'paid', '--lifetime',
    '--machine-guid', 'TEST-MACHINE-1',
    '--features', 'pos',
    '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code === 0, r.stderr);
  const { payload } = claimsOf(readEnvelope(outPath));
  equal(payload.exp - payload.iat, 36500 * DAY, 'lifetime term');
  equal(payload.license_expires_at, null, 'license_expires_at');
});

check('license_expires_at mirrors exp for a paid license', () => {
  issueWith(['--type', 'paid', '--months', '12', '--features', 'pos']);
  const { payload } = claimsOf(readEnvelope(outPath));
  equal(
    new Date(payload.license_expires_at).getTime(),
    payload.exp * 1000,
    'license_expires_at',
  );
});

// ── AC3: signature verifies against the matching public key ───────────────
check('AC3  the signature verifies against the matching public key', () => {
  issue();
  const env = readEnvelope(outPath);
  const [h, p, s] = env.lease.split('.');
  const verifier = crypto.createVerify('RSA-SHA256');
  verifier.update(`${h}.${p}`);
  assert(verifier.verify(publicKey, Buffer.from(s, 'base64url')), 'bad signature');
});

check('AC6  the same document does NOT verify against a different key', () => {
  issue();
  const env = readEnvelope(outPath);
  const [h, p, s] = env.lease.split('.');
  const other = crypto.generateKeyPairSync('rsa', { modulusLength: 2048 });
  const verifier = crypto.createVerify('RSA-SHA256');
  verifier.update(`${h}.${p}`);
  assert(!verifier.verify(other.publicKey, Buffer.from(s, 'base64url')),
    'a foreign key must not verify this document');
});

// ── AC10: determinism ─────────────────────────────────────────────────────
check('AC10 same claims + same key produce a byte-identical signature', () => {
  issue(['--license-key', 'MO2-DETERMINISM-1', '--customer', 'ثابت']);
  const first = readEnvelope(outPath).lease;

  // Re-sign the exact same payload (same iat) to isolate the signature step.
  issue(['--license-key', 'MO2-DETERMINISM-1', '--customer', 'ثابت']);
  const env = readEnvelope(outPath);
  const { payload } = claimsOf(env);
  const header = { alg: 'RS256', typ: 'JWT' };
  const b64 = (o) => Buffer.from(JSON.stringify(o), 'utf8').toString('base64url');
  const unsigned = `${b64(header)}.${b64(payload)}`;
  const signer = crypto.createSign('RSA-SHA256');
  signer.update(unsigned);
  const sig = signer.sign(privateKey, 'base64url');
  equal(sig, env.lease.split('.')[2], 'RS256 is deterministic');
  assert(typeof first === 'string' && first.split('.').length === 3, 'shape');
});

check('AC10 identical input produces an identical document', () => {
  issue(['--license-key', 'MO2-STABLE-1']);
  const a = claimsOf(readEnvelope(outPath)).payload;
  issue(['--license-key', 'MO2-STABLE-1']);
  const b = claimsOf(readEnvelope(outPath)).payload;
  // iat may tick over a second between the two runs; everything else must match.
  equal(b.exp - b.iat, a.exp - a.iat, 'term');
  equal(b.license_key, a.license_key, 'key');
});

// ── AC7: features are carried verbatim (the client trims them) ────────────
check('AC7  unknown feature names are carried, and the client trims them', () => {
  issue(['--features', 'pos,quantum_teleportation']);
  const { payload } = claimsOf(readEnvelope(outPath));
  assert(payload.features.includes('pos'), 'pos kept');
  assert(payload.features.includes('quantum_teleportation'),
    'the issuer does not silently second-guess the operator; trimming is a client concern');
});

check('whitespace in --features is tolerated', () => {
  issue(['--features', ' pos , inventory ,, reports ']);
  const { payload } = claimsOf(readEnvelope(outPath));
  equal(payload.features.join(','), 'pos,inventory,reports', 'features');
});

// ── AC8: the guards ───────────────────────────────────────────────────────
check('AC8  refuses a key inside the repository', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X',
    '--features', 'pos', '--out', outPath,
    '--key', path.join(REPO_ROOT, 'some_key.pem'),
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('داخل المستودع'), 'Arabic guard message: ' + r.stderr);
});

check('AC8  refuses test/fixtures/license/test_private.pem by path', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X',
    '--features', 'pos', '--out', outPath,
    '--key', path.join(REPO_ROOT, 'test', 'fixtures', 'license', 'test_private.pem'),
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('test_private.pem'), 'guard message: ' + r.stderr);
});

check('AC8  refuses a renamed copy of test_private.pem by CONTENT', () => {
  const tracked = path.join(REPO_ROOT, 'test', 'fixtures', 'license', 'test_private.pem');
  if (!fs.existsSync(tracked)) {
    console.log('       (skipped: no tracked test key on this branch)');
    return;
  }
  const disguised = path.join(tmpDir, 'totally_legit_name.pem');
  fs.copyFileSync(tracked, disguised);
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X',
    '--features', 'pos', '--out', outPath, '--key', disguised,
  ]);
  assert(r.code !== 0, 'must refuse a disguised test key');
  assert(r.stderr.includes('مطابق بالمحتوى'), 'guard message: ' + r.stderr);
});

check('AC8  refuses an output path inside the repository', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X', '--features', 'pos',
    '--key', keyPath,
    '--out', path.join(REPO_ROOT, 'license.madarlicense'),
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('داخل المستودع'), 'guard message: ' + r.stderr);
});

check('AC8  writes nothing when a guard trips', () => {
  const inside = path.join(REPO_ROOT, 'should_never_exist.madarlicense');
  run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X', '--features', 'pos',
    '--key', keyPath, '--out', inside,
  ]);
  assert(!fs.existsSync(inside), 'no artifact may be left behind');
});

// ── edge cases ────────────────────────────────────────────────────────────
check('--days 0 is refused', () => {
  const r = run([
    '--type', 'trial', '--days', '0', '--machine-guid', 'X', '--features', 'pos',
    '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('أكبر من صفر'), 'message: ' + r.stderr);
});

check('empty --features is refused with a clear message', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X', '--features', ' , , ',
    '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('فارغ'), 'message: ' + r.stderr);
});

check('a missing duration is refused', () => {
  const r = run([
    '--type', 'trial', '--machine-guid', 'X', '--features', 'pos',
    '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('المدة'), 'message: ' + r.stderr);
});

check('--days and --months together are refused', () => {
  const r = run([
    '--type', 'paid', '--days', '30', '--months', '12', '--machine-guid', 'X',
    '--features', 'pos', '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code !== 0, 'must refuse');
});

check('a missing machine guid is refused', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--features', 'pos',
    '--key', keyPath, '--out', outPath,
  ]);
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('--machine-guid'), 'message: ' + r.stderr);
});

check('a missing key is refused', () => {
  const r = run([
    '--type', 'trial', '--days', '7', '--machine-guid', 'X', '--features', 'pos',
    '--out', outPath,
  ], { env: { ...process.env, MADAR_ISSUER_KEY_FILE: '' } });
  assert(r.code !== 0, 'must refuse');
  assert(r.stderr.includes('MADAR_ISSUER_KEY_FILE'), 'message: ' + r.stderr);
});

check('MADAR_ISSUER_KEY_FILE is honoured', () => {
  const alt = path.join(tmpDir, 'via_env.madarlicense');
  const stdout = execFileSync(process.execPath, [
    ISSUER, '--type', 'trial', '--days', '3', '--machine-guid', 'X',
    '--features', 'pos', '--out', alt,
  ], {
    encoding: 'utf8',
    env: { ...process.env, MADAR_ISSUER_KEY_FILE: keyPath },
  });
  assert(fs.existsSync(alt), 'document written via env key');
  assert(stdout.includes('3 يوماً'), 'reports the term');
});

check('--install-uuid binding carries the install id, not the machine id', () => {
  issue(['--bind', 'install', '--install-uuid', 'INSTALL-ABC']);
  const { payload } = claimsOf(readEnvelope(outPath));
  equal(payload.machine_guid, '', 'machine_guid empty');
  equal(payload.install_uuid, 'INSTALL-ABC', 'install_uuid');
});

check('--bind both carries both ids', () => {
  issue(['--bind', 'both', '--machine-guid', 'M1', '--install-uuid', 'I1']);
  const { payload } = claimsOf(readEnvelope(outPath));
  equal(payload.machine_guid, 'M1', 'machine');
  equal(payload.install_uuid, 'I1', 'install');
});

// ── AC9: clock offset is printed ──────────────────────────────────────────
check('AC9  the device clock offset is printed at issuance', () => {
  const r = issue();
  assert(r.stdout.includes('إزاحة ساعة الجهاز'), 'clock offset line missing');
  assert(r.stdout.includes('device_clock_offset_seconds'), 'offset in envelope');
  const env = readEnvelope(outPath);
  equal(env.device_clock_offset_seconds, 0, 'offset value');
  assert(env.device_clock_utc, 'device clock recorded');
});

check('AC9  customer name is recorded outside the signature', () => {
  issue(['--customer', 'سلسلة البركة']);
  const env = readEnvelope(outPath);
  equal(env.customer, 'سلسلة البركة', 'customer');
  const { payload } = claimsOf(env);
  assert(!JSON.stringify(payload).includes('سلسلة البركة'),
    'the customer name must not enter the signed claims');
});

// ── keys are never printed ────────────────────────────────────────────────
check('the private key never reaches stdout or the document', () => {
  const r = issue();
  const env = readEnvelope(outPath);
  const body = r.stdout + JSON.stringify(env);
  assert(!body.includes('PRIVATE KEY'), 'no PEM material anywhere');
  assert(!body.includes(privateKey.split('\n')[1]), 'no key body leaked');
});

check('the issuer file itself contains no key material', () => {
  const src = fs.readFileSync(ISSUER, 'utf8');
  assert(!src.includes('PRIVATE KEY-----'), 'no embedded PEM');
});

// ── cleanup ───────────────────────────────────────────────────────────────
fs.rmSync(tmpDir, { recursive: true, force: true });

console.log('\n' + passed + ' passed, ' + failures.length + ' failed\n');
if (failures.length) {
  failures.forEach((f) => console.log('  ✖ ' + f));
  process.exit(1);
}